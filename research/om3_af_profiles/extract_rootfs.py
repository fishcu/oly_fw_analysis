"""Extract regular files only; preserve symlinks/devices as inventory, not host objects."""
import hashlib,json,struct,subprocess,collections
from pathlib import Path,PurePosixPath
root=Path(__file__).resolve().parent
out=root/'analysis/embedded'
seven=r'C:\Program Files\7-Zip\7z.exe'
archive=out/'rootfs.squashfs'
listing=subprocess.check_output([seven,'l','-slt',str(archive)],text=True,encoding='utf-8')
(out/'rootfs-7zip-listing.txt').write_text(listing,encoding='utf-8')
records=[]
for block in listing.split('----------',1)[1].strip().split('\n\n'):
    fields=dict(line.split(' = ',1) for line in block.splitlines() if ' = ' in line)
    if 'Path' not in fields:continue
    path=PurePosixPath(fields['Path'].replace('\\','/'))
    if path.is_absolute() or '..' in path.parts or ':' in str(path):raise ValueError('Unsafe archive path')
    records.append(fields)
regular=[r['Path'] for r in records if r.get('Mode','').startswith('-')]
groups=collections.defaultdict(list)
for name in regular:groups[name.casefold()].append(name)
collision_names={name for group in groups.values() if len(group)>1 for name in group}
filelist=out/'rootfs-regular-files.txt'
filelist.write_text('\n'.join(name for name in regular if name not in collision_names)+'\n',encoding='utf-8')
destination=out/'rootfs'
subprocess.run([seven,'x','-y','-ssc',str(archive),'-o'+str(destination),'-i@'+str(filelist)],check=True,capture_output=True)
stored={}
expected_sizes={r['Path']:int(r['Size']) for r in records if r.get('Mode','').startswith('-')}
for name in regular:
    if name in collision_names:
        token=hashlib.sha256(name.encode()).hexdigest()[:16]
        p=out/'rootfs-case-sensitive'/token/Path(name).name
        p.parent.mkdir(parents=True,exist_ok=True)
        with p.open('wb') as f:
            subprocess.run([seven,'x','-so','-ssc',str(archive),name],stdout=f,stderr=subprocess.PIPE,check=True)
        assert p.stat().st_size==expected_sizes[name],name
        stored[name]=p
    else:stored[name]=destination/name
elfs=[]
for name in regular:
    p=stored[name]
    b=p.read_bytes()
    if b[:4]!=b'\x7fELF':continue
    endian='<' if b[5]==1 else '>'
    etype,machine=struct.unpack_from(endian+'HH',b,16)
    elfs.append(dict(path=name,storage_path=str(p.relative_to(out)),case_collision=name in collision_names,
                     bytes=len(b),sha256=hashlib.sha256(b).hexdigest(),elf_class=b[4],machine=machine,type=etype))
# Remove only the ambiguous files generated by the first extraction. Authoritative
# case-distinct copies are now stored and size-checked above; never delete recursively.
for name in collision_names:
    ambiguous=destination/name
    if ambiguous.exists():ambiguous.unlink()
(out/'rootfs-inventory.json').write_text(json.dumps(dict(entries=records,regular_files=len(regular),
    case_collision_files=len(collision_names),stored_files={k:str(v.relative_to(out)) for k,v in stored.items()},elfs=elfs),indent=2)+'\n')
print(json.dumps(dict(entries=len(records),regular_files=len(regular),elf_count=len(elfs)),indent=2))
